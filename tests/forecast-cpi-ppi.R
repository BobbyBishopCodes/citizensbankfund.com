sys.source("scripts/forecast-cpi-ppi.R", envir = environment())
months = seq(as.Date("2010-01-01"), as.Date("2026-08-01"), by = "month")
values = 100 + seq_along(months) * 0.3 + sin(seq_along(months) / 6)
missing = months != as.Date("2025-10-01")
levels = xts::xts(values[missing], order.by = months[missing])
changes = monthly_change(levels, "2010-01", "2026-08")
stopifnot(is.na(window(changes, start = c(2025, 10), end = c(2025, 11))[1]))
stopifnot(is.na(window(changes, start = c(2025, 10), end = c(2025, 11))[2]))
stopifnot(abs(as.numeric(tail(time(changes), 1)) - (2026 + 7 / 12)) < 1e-8)
result = forecast_change(changes, c(1, 0, 2), "2026-09")
stopifnot(is.finite(result$point), length(result$range80) == 2L)
cat("Forecast calendar checks passed.\n")
